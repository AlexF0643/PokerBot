"""Recalculate the EQUITY table in model.py. Not part of the submission.

    python -m tools.build_preflop_table

Estimates each of the 169 starting hands' equity against a random hand, heads-up,
and writes tools/new_equity_table.py to paste into model.py.
"""

import random

from model import score_hand

RANKS = "23456789TJQKA"
SAMPLES = 20000


def equity(first, second, rng):
    deck = [card for card in range(52) if card not in (first, second)]
    won = 0.0
    for _ in range(SAMPLES):
        cards = rng.sample(deck, 7)
        board = cards[2:]
        mine = score_hand([first, second, *board])
        theirs = score_hand(cards)
        won += 1.0 if mine > theirs else 0.5 if mine == theirs else 0.0
    return won / SAMPLES


def main():
    rng = random.Random(169)
    table = {}
    for high in range(12, -1, -1):
        for low in range(high, -1, -1):
            if high == low:
                table[RANKS[high] * 2] = equity(high * 4, high * 4 + 1, rng)
                continue
            names = RANKS[high] + RANKS[low]
            table[names + "s"] = equity(high * 4, low * 4, rng)
            table[names + "o"] = equity(high * 4, low * 4 + 1, rng)
    with open("tools/new_equity_table.py", "w", encoding="utf-8") as file:
        file.write('"""Heads-up equity of each starting hand against a random '
                   'hand.\n\nGenerated by tools/build_preflop_table.py.\n"""\n\n')
        file.write("EQUITY = {\n")
        for name, value in sorted(table.items(), key=lambda item: -item[1]):
            file.write(f'    "{name}": {value:.4f},\n')
        file.write("}\n")


if __name__ == "__main__":
    main()
